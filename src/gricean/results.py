"""The generated blocks of `paper/RESULTS.md` (design of 2026-11-21).

The page is written by hand. Between a pair of marker lines its text is generated here, from the
tables `gricean report` committed under `paper/<ladder>/`; nothing is recomputed from `data/`, so
the page cannot disagree with the tables the paper cites. The opening marker names the table and
the cells it shows.
"""
from __future__ import annotations

import re
from pathlib import Path

import pandas as pd

from .report import MAIN_LANGUAGE, _suffix
from .stimuli import QUOTAS

TABLES = ("intent", "logodds", "kappa", "termination", "summary")
CELL_TABLES = ("intent", "logodds")             # read from a CSV of category x condition by model
LISTS = ("condition", "category", "models")     # keys whose value is a comma-separated list
KEYS = ("table", "ladder", "language", *LISTS)

MODEL_LABELS = {
    "olmo_stage1": "Stage 1", "olmo_base": "Base", "olmo_sft": "SFT", "olmo_dpo": "DPO", "olmo_instruct": "Instruct",
    "olmo_stage1_alpaca": "Stage 1 Alpaca", "olmo_n500": "500", "olmo_n2000": "2,000", "olmo_full": "All pairs",
    "olmo_format_only": "Format only",
}
LANGUAGE_NAMES = {"en": "English", "pt": "Portuguese"}
CAPTIONS = {
    "intent": "Line 1. {language}, {conditions}: responses coded `intended`, of the items in each cell (`{file}`).",
    "logodds": ("Line 2. {language}, {conditions}: mean log-odds of the intended over the literal continuation, "
                "with its bootstrap interval (`{file}`)."),
}
KAPPA_NAMES = {
    "cohen_kappa_intent": "`intent`",
    "cohen_kappa_correctness_same_intent": "`correctness`, rows with the same `intent`",
    "cohen_kappa_correctness_all": "`correctness`, all rows",
}
OPEN_PREFIX = "<!-- generated by `gricean results`: "    # an opening marker: this, what to show, OPEN_SUFFIX
OPEN_SUFFIX = " -->"
CLOSE = "<!-- end of generated block: edits above this line are overwritten -->"
VERDICTS = ("held", "failed", "mixed")
CLAIM = re.compile(r"### (\d+[a-z]?)\. (.+)")              # `### 1c. Rises sharply at SFT`
DECISION = re.compile(r"### (D\d+)\. (.+)")                # `### D2. Base as a column or a dose note`
FIELDS = {"claim": {"- Line 1 verdict:": "line1", "- Line 2 verdict:": "line2", "- Support:": "support"},
          "decision": {"- Decision:": "decision"}}
NO_VALUE = "—"
MINUS = "−"


def parse_spec(text: str) -> dict:
    """What an opening marker asks for: `table=intent ladder=olmo condition=full,stripped` as a dict."""
    spec: dict = {}
    for word in text.split():
        key, eq, value = word.partition("=")
        if not eq or not value:
            raise ValueError(f"{word!r} is not of the form key=value")
        if key not in KEYS:
            raise ValueError(f"unknown key {key!r} (allowed: {', '.join(KEYS)})")
        spec[key] = value.split(",") if key in LISTS else value
    table = spec.get("table")
    if table not in TABLES:
        raise ValueError(f"table must be one of {', '.join(TABLES)}; found {table!r}")
    if table != "summary" and "ladder" not in spec:
        raise ValueError(f"table={table} needs ladder=")
    if table in CELL_TABLES and "condition" not in spec:
        raise ValueError(f"table={table} needs condition=")
    if table not in CELL_TABLES:                # these blocks show one file whole: there is nothing to select
        if extra := [k for k in spec if k in (*LISTS, "language") or (k == "ladder" and table == "summary")]:
            raise ValueError(f"table={table} does not take {', '.join(extra)}")
    spec.setdefault("language", MAIN_LANGUAGE)
    if spec["language"] not in QUOTAS:
        raise ValueError(f"language must be one of {', '.join(QUOTAS)}; found {spec['language']!r}")
    return spec


def _markdown_table(header: list[str], rows: list[list[str]]) -> str:
    """A table padded to equal column widths, so that the source of the page reads as a table too."""
    widths = [max(3, *(len(r[i]) for r in [header, *rows])) for i in range(len(header))]
    line = lambda cells: "| " + " | ".join(c.ljust(w) for c, w in zip(cells, widths)) + " |"   # noqa: E731
    return "\n".join([line(header), line(["-" * w for w in widths]), *(line(r) for r in rows)])


def _label(category: str) -> str:
    return category.replace("_", " ").capitalize()


def _number(x: float) -> str:
    return f"{round(float(x), 2) + 0.0:.2f}".replace("-", MINUS)      # `+ 0.0`: no "-0.00"


def _count(rate: float, n: int, where: str) -> int:
    k = rate * n
    if abs(k - round(k)) > 1e-6:                # a rate that is not k/n: the quota is not this table's; do not round
        raise ValueError(f"{where}: rate {rate} is not a count out of {n}")
    return round(k)


def _cell_table(spec: dict, paper: Path) -> str:
    name = f"{spec['table']}{_suffix(spec['language'])}.csv"
    shown = f"paper/{spec['ladder']}/{name}"
    path = Path(paper) / spec["ladder"] / name
    if not path.exists():
        raise ValueError(f"{shown} is not there")
    df = pd.read_csv(path, header=[0, 1], index_col=[0, 1])
    in_file = list(dict.fromkeys(df.columns.get_level_values(0)))
    models = spec.get("models", in_file)
    if missing := [m for m in models if m not in in_file]:
        raise ValueError(f"{shown} has no model {', '.join(missing)}")
    categories = list(dict.fromkeys(df.index.get_level_values(0)))
    if "category" in spec:
        if missing := [c for c in spec["category"] if c not in categories]:
            raise ValueError(f"{shown} has no category {', '.join(missing)}")
        categories = [c for c in categories if c in spec["category"]]
    conditions = spec["condition"]
    several = len(conditions) > 1
    quota, control_quota = QUOTAS[spec["language"]]
    rows, totals = [], {c: [] for c in conditions}          # totals: per condition, one list of counts per row
    for category in categories:
        for condition in conditions:
            if (category, condition) not in df.index:
                if "category" in spec:
                    raise ValueError(f"{shown} has no row {category}, {condition}")
                continue                                    # not every category exists in every version
            label = f"{_label(category)}, `{condition}`" if several else _label(category)
            cells, counts = [], []
            for model in models:
                if spec["table"] == "intent":
                    n = control_quota if condition == "control" else quota
                    rate = df.loc[(category, condition), (model, "intended")]
                    k = None if pd.isna(rate) else _count(rate, n, f"{shown}, {category}, {condition}, {model}")
                    counts.append((k, n))
                    cells.append(NO_VALUE if k is None else f"{k}/{n}")
                else:
                    mean, low, high = (df.loc[(category, condition), (model, c)] for c in ("mean", "ci_low", "ci_high"))
                    cells.append(NO_VALUE if pd.isna(mean) else f"{_number(mean)} [{_number(low)}, {_number(high)}]")
            rows.append([label, *cells])
            totals[condition].append(counts)
    if empty := [c for c in conditions if not totals[c]]:
        raise ValueError(f"{shown} has no condition {', '.join(empty)}")
    if spec["table"] == "intent":                           # the one sum on the page; Line 2 means are never pooled
        for condition in conditions:
            per_row = totals[condition]
            if len(per_row) < 2:
                continue
            label = f"All {len(per_row)} categories" + (f", `{condition}`" if several else "")
            cells = []
            for column in zip(*per_row):
                known = all(k is not None for k, _ in column)
                cells.append(f"{sum(k for k, _ in column)}/{sum(n for _, n in column)}" if known else NO_VALUE)
            rows.append([label, *cells])
    caption = CAPTIONS[spec["table"]].format(language=LANGUAGE_NAMES[spec["language"]], file=shown,
                                             conditions=", ".join(f"`{c}`" for c in conditions))
    return caption + "\n\n" + _markdown_table(["Category", *(MODEL_LABELS.get(m, m) for m in models)], rows)


def _text_file(spec: dict, paper: Path) -> tuple[list[str], str]:
    shown = f"paper/{spec['ladder']}/{spec['table']}.txt"
    path = Path(paper) / spec["ladder"] / f"{spec['table']}.txt"
    if not path.exists():
        raise ValueError(f"{shown} is not there")
    return path.read_text().splitlines(), shown


def _kappa(spec: dict, paper: Path) -> str:
    lines, shown = _text_file(spec, paper)
    found = [m for m in (re.fullmatch(r"(\S+)=(\S+) n=(\d+) same=(\d+)", line.strip()) for line in lines) if m]
    if not found:
        raise ValueError(f"{shown} holds no agreement measure")
    items = [f"- {KAPPA_NAMES.get(name, name)}: κ = {value} (n = {n}, same code on {same})" for name, value, n, same
             in (m.groups() for m in found)]
    return "\n".join([f"Agreement between the two coders, one sample for both ladders (`{shown}`).", "", *items])


def _termination(spec: dict, paper: Path) -> str:
    lines, shown = _text_file(spec, paper)
    limit = next((m[1] for m in (re.match(r"limit=(\d+)", line) for line in lines) if m), None)
    turns = next((line.split()[1:] for line in lines if line.startswith("complete_turns ")), None)
    if limit is None or not turns:
        raise ValueError(f"{shown} holds no `limit=` or no `complete_turns` line")
    models, counts = zip(*(pair.split("=", 1) for pair in turns))
    out = [f"Post hoc (spec §13.1). English, `full`, dissociation items: responses coded `intended` that ended "
           f"before the limit of {limit} tokens (`{shown}`).", "",
           _markdown_table(["", *(MODEL_LABELS.get(m, m) for m in models)], [["Complete turns", *counts]])]
    for line in lines:                                      # the comparison fixed in advance, where the ladder has one
        if m := re.fullmatch(r"(\S+) vs (\S+): (.+)", line.strip()):
            first, second = (MODEL_LABELS.get(name, name) for name in m.groups()[:2])
            v = dict(pair.split("=", 1) for pair in m[3].split() if "=" in pair)
            if lacking := [k for k in ("only_first", "only_second", "mcnemar_exact_p") if k not in v]:
                raise ValueError(f"{shown}: the comparison line has no {', '.join(lacking)}")
            out += ["", f"Exploratory comparison fixed in advance, {first} against {second}: {v['only_first']} items one "
                        f"way, {v['only_second']} the other; exact McNemar p = {float(v['mcnemar_exact_p']):.2f}."]
    return "\n".join(out)


def render_block(spec: dict, paper: Path) -> str:
    """The Markdown of one generated block, without its markers and without a final line break."""
    if spec["table"] in CELL_TABLES:
        return _cell_table(spec, paper)
    if spec["table"] == "kappa":
        return _kappa(spec, paper)
    if spec["table"] == "termination":
        return _termination(spec, paper)
    raise ValueError(f"table={spec['table']} cannot be rendered here")


def _is_open(line: str) -> bool:
    return line.rstrip().startswith(OPEN_PREFIX) and line.rstrip().endswith(OPEN_SUFFIX)


def _entries(page: str) -> list[dict]:
    """The claims and decisions of the page, in order, with what the author wrote on their lines.

    Only the author's text is read: a line inside a generated block is never taken for a heading or a verdict."""
    entries, seen, current, inside = [], {}, None, False
    for n, line in enumerate(page.split("\n"), 1):
        if _is_open(line) or line.strip() == CLOSE:
            inside = _is_open(line)
            continue
        if inside:
            continue
        if line.startswith("#"):                            # any heading ends the section before it
            current = None
            for kind, pattern in (("claim", CLAIM), ("decision", DECISION)):
                if m := pattern.fullmatch(line.strip()):
                    if m[1] in seen:
                        raise ValueError(f"line {n}: the id {m[1]} is already used at line {seen[m[1]]}")
                    seen[m[1]] = n
                    current = {"kind": kind, "id": m[1], "title": m[2]}
                    entries.append(current)
            continue
        if current is None:
            continue
        for prefix, field in FIELDS[current["kind"]].items():
            if line.strip().startswith(prefix):
                value = line.strip()[len(prefix):].strip()
                if field in ("line1", "line2"):
                    if value and value.lower() not in VERDICTS:
                        raise ValueError(f"line {n}: a verdict is {', '.join(VERDICTS[:-1])} or {VERDICTS[-1]}, "
                                         f"or is left empty; found {value!r}")
                    value = value.lower()
                current[field] = value
    return entries


def render_summary(page: str) -> str:
    """Every claim with its verdicts, and every decision, as the author's lines stand now."""
    entries = _entries(page)
    cell = lambda text: text.replace("|", "\\|")                                         # noqa: E731
    shown = lambda e, field: NO_VALUE if field not in e else (cell(e[field]) or "open")  # noqa: E731
    claims = [[cell(f"{e['id']} {e['title']}"), shown(e, "line1"), shown(e, "line2"), shown(e, "support")]
              for e in entries if e["kind"] == "claim"]
    decisions = [[cell(f"{e['id']} {e['title']}"), shown(e, "decision")] for e in entries if e["kind"] == "decision"]
    tables = ([_markdown_table(["Claim", "Line 1", "Line 2", "Support"], claims)] if claims else []) + \
             ([_markdown_table(["Decision", "Status"], decisions)] if decisions else [])
    return "\n\n".join(tables) or "No claim on this page yet."


def refresh(page: str, paper: Path) -> str:
    """The page with every generated block rewritten; every line outside the blocks is returned as it came."""
    summary = render_summary(page)                          # first: a verdict that cannot be read stops everything
    out, opened = [], None
    for n, line in enumerate(page.split("\n"), 1):
        if line.startswith("<!-- generated"):
            if opened:
                raise ValueError(f"line {n}: a generated block opens here, but the one opened at line {opened} "
                                 f"is not closed")
            if not _is_open(line):
                raise ValueError(f"line {n}: not a marker `gricean results` can read; it must be "
                                 f"{OPEN_PREFIX}table=...{OPEN_SUFFIX}")
            try:
                spec = parse_spec(line.rstrip()[len(OPEN_PREFIX):-len(OPEN_SUFFIX)])
                block = summary if spec["table"] == "summary" else render_block(spec, paper)
            except ValueError as e:
                raise ValueError(f"line {n}: {e}") from None
            out += [line, "", block, ""]
            opened = n
        elif line.strip() == CLOSE:
            if not opened:
                raise ValueError(f"line {n}: a generated block ends here, but none is open")
            out.append(line)
            opened = None
        elif not opened:
            out.append(line)
    if opened:
        raise ValueError(f"line {opened}: the generated block opened here is never closed")
    return "\n".join(out)


def update(page_path: Path, paper: Path, check: bool = False) -> bool:
    """Rewrite the page's generated blocks. True when the file already held them; with `check`, never write."""
    old = Path(page_path).read_text(encoding="utf-8")
    new = refresh(old, paper)                               # raises before anything is written
    if new != old and not check:
        Path(page_path).write_text(new, encoding="utf-8")
    return new == old
